"""
Unified LangGraph State Schema

Defines the shared State object passed cyclically across all specialized AI agents
during autonomous research interpretation and sandboxed execution loops.
"""

from typing import List, Dict, Any, Optional, TypedDict
from typing_extensions import Annotated
import operator
from langgraph.graph.message import add_messages
# TODO: Import Pydantic BaseModel or TypedDict depending on LangGraph configuration preference


class ExecutionErrorTrace(TypedDict):
    """
    Representation of a failed execution run returned from the Docker Sandbox.
    """
    attempt_num: int
    exception_type: str
    traceback: str
    failing_line_content: str
    cuda_error_detected: bool


class SoulGraphState(TypedDict):
    """
    Unified LangGraph state machine structure for autonomous code translation.
    
    # TODO: Modify annotation reducers if accumulating logs over multiple agent passes.
    """
    # Target Information
    paper_id: str
    target_component: str               # Explicit architecture block being translated (e.g., "Transformer Encoder")
    target_framework: str               # "PyTorch" or "JAX"
    
    # Retrieved Knowledge (Filled by Researcher Agent)
    paper_context: Dict[str, Any]       # Subgraph topology from Neo4j & similar math chunks from Vector DB
    relevant_formulas: List[str]        # Raw LaTeX expressions mapped to this component
    hyperparameters: Dict[str, Any]     # Discovered default sizes (e.g., hidden_dim=512, heads=8)
    
    # Architecture Blueprint (Filled by Architect Agent)
    structural_skeleton: str            # Python classes with explicit docstrings and `# [B, S, D] -> ...` shape annotations
    expected_inputs: Dict[str, str]     # Shape definitions for generating synthetic dummy test tensors
    
    # Generated Implementation & Sandbox Validation (Filled by Coder & Sandbox)
    current_code: str                   # Complete runnable executable PyTorch/JAX implementation
    attempt_count: int                  # Monotone iteration tracker to prevent infinite loops (Max = 5)
    execution_status: str               # "UNTESTED", "STATIC_ANALYSIS_FAILED", "RUNTIME_ERROR", "SUCCESS"
    
    # Error Diagnostic Accumulator (Filled by Critic & Docker Sandbox)
    messages:Annotated[list,add_messages]
    # Annotated with operator.add to append historical logs across cyclic failures
    execution_logs: Annotated[List[ExecutionErrorTrace], operator.add]
    critic_feedback: str                # Guidance generated by Critic Agent on why tensor math failed
    # Telemetry Output (Upon Success)
    tensor_shape_traces: Dict[str, Any] # Captured runtime dimensions per layer for Explainer UI tooltips
