"""
Visual Tensor Tracing & Telemetry Wrappers

Injected into generated model execution scripts inside the sandbox to capture and serialize
exact tensor dimensionalities (e.g., [batch_size, sequence_length, hidden_dim]) layer-by-layer
during forward passes without triggering out-of-memory overheads.
"""


def get_telemetry_tracker_code() -> str:
    """
    Returns a stringified self-contained Python module (`telemetry_tracker.py`) to be written
    directly into the Docker volume mount directory alongside user scripts.
    
    Returns:
        str: Python source code for automatic layer forward hooks and shape logging.
    """
    return """import json
import atexit
import torch
import torch.nn as nn

shape_log = {}

def make_hook(layer_name):
    def hook_fn(module, input, output):
        inp_tensor = input[0] if isinstance(input, tuple) and len(input) > 0 else input
        out_tensor = output[0] if isinstance(output, tuple) and len(output) > 0 else output
        shape_log[layer_name] = {
            "input": str(list(inp_tensor.shape)),
            "output": str(list(out_tensor.shape))
        }
    return hook_fn

def save_tensor_traces():
    with open("/tmp/tensor_traces.json", "w") as f:
        json.dump(shape_log, f, indent=2)

atexit.register(save_tensor_traces)

def attach_tensor_tracer(model):
    for name, module in model.named_modules():
        is_leaf = len(list(module.children())) == 0
        is_target_layer = isinstance(module, (nn.Linear, nn.Conv2d, nn.LayerNorm, nn.MultiheadAttention))
        if is_leaf and is_target_layer:
            module.register_forward_hook(make_hook(name))
"""

def inject_telemetry_wrapper(original_script: str) -> str:
    """
    Appends instrumentation initialization calls into an AI-generated model file.
    
    Args:
        original_script (str): Code generated by Coder Agent.
        
    Returns:
        str: Instrumented code ready to capture tensor flow telemetry during dummy run.
        
    # TODO: Prepend `from telemetry_tracker import attach_tensor_tracer` to script imports.
    # TODO: Inject call `attach_tensor_tracer(model)` immediately before the execution of the forward pass.
    """
    import re

    import_line = "from telemetry_tracker import attach_tensor_tracer"
    tracer_call = "attach_tensor_tracer(model)"

    # Idempotency: already instrumented -> f(f(x)) == f(x)
    if tracer_call in original_script:
        return original_script

    target = re.compile(r"(?:^|=|return)\s*model\(")

    lines = original_script.splitlines()
    result = []
    attached = False

    for line in lines:
        # Attach once, at the first forward call only
        if not attached and target.search(line):
            leading_whitespace = re.match(r"[ \t]*", line).group(0)
            result.append(leading_whitespace + tracer_call)
            attached = True
        result.append(line)

    # Fail loud: the Critic must know the tracer was never attached
    if not attached:
        raise ValueError("inject_telemetry_wrapper: no forward call `model(...)` found in script")

    # `from __future__` imports must stay the first statements
    insert_at = 0
    for i, line in enumerate(result):
        if line.startswith("from __future__"):
            insert_at = i + 1
    if import_line not in result:
        result.insert(insert_at, import_line)

    new_text = "\n".join(result)
    if original_script.endswith("\n"):
        new_text += "\n"
    return new_text
